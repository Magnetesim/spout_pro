/* Headless port of spout.c game logic, for training.
 *
 * The per-frame logic is a line-by-line port of pceAppProc() from
 * ../spout/spout.c (in-game phase only). Globals and static locals live in
 * the Spout struct so many games can run side by side, and rand() is
 * replaced by a per-game seeded generator. tests/fidelity checks that this
 * port produces the same frames as the original.
 */
#ifndef SPOUT_CORE_H
#define SPOUT_CORE_H

#include <stdint.h>

/* Same values as the macros at the top of spout.c */
#define SP_FRAMERATE 50
#define SP_MAX_GRAIN 500
#define SP_MAX_SPEED 256
#define SP_SPEED_FACTOR 128
#define SP_GRAIN_FACTOR 1

/* Screen buffer (vbuff) is 128x88: rows 2..79 are the play area, 82..87 the HUD. */
#define SP_W 128
#define SP_SCREEN_H 88
#define SP_PLAY_Y0 2
#define SP_PLAY_H 78

/* Held-button bits, same as spout.h */
#define SP_PAD_RI 0x01
#define SP_PAD_LF 0x02
#define SP_PAD_A 0x20

typedef struct {
	int16_t x, y;
} SpSVec;

typedef struct {
	int16_t next, prev; /* indices into grain[], -1 = none */
	SpSVec s, v;
	int16_t pos;
	uint8_t color;
} SpGrain;

typedef struct {
	uint8_t vbuff[SP_W * SP_SCREEN_H]; /* what the player sees, colors 0..3 */
	uint8_t vbuff2[128 * 128];         /* world ring buffer: color | flags | hp */
	SpGrain grain[SP_MAX_GRAIN];
	int16_t v2g[128 * 128]; /* world pixel -> grain index, -1 = none */
	int16_t use_head, free_head;

	int64_t mPosX, mPosY, mSpeedX, mSpeedY; /* `long` in the original */
	int32_t mR;
	int32_t nGrain;
	int32_t time, score, height, dispscore;
	int32_t dispPos, upperLine, rollCount;
	int32_t gameover;
	int32_t gx[5];  /* static local in the original */
	int32_t gPhase; /* static local in the original */
	uint64_t rng;

	/* Events from the most recent sp_frame(), used for rewards. */
	int32_t ev_scored;     /* height++ events while height > 0 */
	int32_t ev_bonus;      /* time-bonus points added to score */
	int32_t ev_barrier;    /* barriers passed (height reached 128k+1) */
	int32_t ev_hits_above; /* terrain hp knocked off near and above the ship */
} Spout;

/* xorshift64*, top 31 bits. Shared with the fidelity test so both sides
 * draw the same numbers. */
static inline int sp_rng_next(uint64_t *state)
{
	uint64_t x = *state;
	x ^= x >> 12;
	x ^= x << 25;
	x ^= x >> 27;
	*state = x;
	return (int)((x * 0x2545F4914F6CDD1DULL) >> 33);
}

uint64_t sp_seed_to_state(uint64_t seed);

/* Start a game exactly like the original does after "press start". */
void sp_reset(Spout *s, uint64_t seed);

/* Start a game at a given height with the ship parked in a small cleared
 * pocket at screen position (x, y), facing mR. Terrain is generated by the
 * game's own scroll routine, so it looks like a normal game at that height. */
void sp_reset_at(Spout *s, uint64_t seed, int height, int x, int y, int mR);

/* Advance one frame (1/50 s) with the given held buttons. */
void sp_frame(Spout *s, int pad);

#endif
